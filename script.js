function setPageControls() {
  const storyContent = getActiveStoryContent();
  const hasPages = Boolean(storyContent && storyContent.pages);

  previousPageButton.disabled = !hasPages || isPageTurning || activePageIndex === 0;
  nextPageButton.disabled = !hasPages || isPageTurning || activePageIndex === storyContent.pages.length - 1;
}

function updateStoryPage() {
  const storyContent = getActiveStoryContent();

  if (!storyContent) {
    return;
  }

  const isEmbeddedBook = Boolean(storyContent.embedSrc);

  storyReader.classList.toggle("embed-mode", isEmbeddedBook);
  storyReader.classList.toggle("square-book", storyContent.pageShape === "square");
  storyReaderTitle.textContent = storyContent.title;

  if (isEmbeddedBook) {
    bookEmbed.src = storyContent.embedSrc;
    bookEmbed.title = storyContent.title;
    bookPageCounter.textContent = "";
    setPageControls();
    return;
  }

  bookEmbed.src = "";

  const page = storyContent.pages[activePageIndex];

  bookPageImage.src = page.src;
  bookPageImage.alt = page.alt;
  bookPageCounter.textContent = `Page ${activePageIndex + 1} of ${storyContent.pages.length}`;
  setPageControls();
}

function openStoryBook(storyKey) {
  activeStory = storyBooks[storyKey];

  if (!activeStory) {
    return;
  }

  activePageIndex = 0;
  pageFlipper.className = "page-flipper";
  updateStoryPage();
  setStoryReaderOpen(true);
}

function changeStoryPage(step) {
  const storyContent = getActiveStoryContent();

  if (!storyContent || !storyContent.pages || isPageTurning) {
    return;
  }

  const nextIndex = activePageIndex + step;

  if (nextIndex < 0 || nextIndex >= storyContent.pages.length) {
    return;
  }

  const currentPage = storyContent.pages[activePageIndex];
  const nextPage = storyContent.pages[nextIndex];
  const direction = step > 0 ? "next" : "previous";

  isPageTurning = true;
  setPageControls();

  flipFrontImage.src = direction === "next" ? currentPage.src : nextPage.src;
  flipFrontImage.alt = "";
  flipBackImage.src = direction === "next" ? nextPage.src : currentPage.src;
  flipBackImage.alt = "";
  pageFlipper.className = `page-flipper flip-${direction}`;

  pageFlipper.addEventListener(
    "animationend",
    (event) => {
      if (event.target !== pageFlipper) {
        return;
      }

      activePageIndex = nextIndex;
      updateStoryPage();
      pageFlipper.className = "page-flipper";
      isPageTurning = false;
      setPageControls();
    },
    { once: true }
  );
}

