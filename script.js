function getSavedLanguage() {
  try {
    return localStorage.getItem("fairyHummingsLanguage");
  } catch (error) {
    return null;
  }
}

function saveLanguage(language) {
  try {
    localStorage.setItem("fairyHummingsLanguage", language);
  } catch (error) {
    return;
  }
}

function getPageName() {
  return window.location.pathname.split("/").pop() || "index.html";
}

function applyTranslations(language) {
  const text = translations[language] || translations.en;

  document.documentElement.lang = language;
  document.title = pageTitles[language][getPageName()] || pageTitles[language]["index.html"];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (text[key]) {
      element.innerHTML = text[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;

    if (text[key]) {
      element.setAttribute("placeholder", text[key]);
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;

    if (text[key]) {
      element.setAttribute("aria-label", text[key]);
    }
  });

  languageSelects.forEach((select) => {
    const englishOption = select.querySelector('option[value="en"]');
    const sinhalaOption = select.querySelector('option[value="si"]');

    if (englishOption) {
      englishOption.textContent = "English";
    }

    if (sinhalaOption) {
      sinhalaOption.textContent = "\u0dc3\u0dd2\u0d82\u0dc4\u0dbd";
    }

    select.value = language;
    select.setAttribute("aria-label", text.selectLanguage);
  });
}

function setLanguage(language) {
  currentLanguage = language === "si" ? "si" : "en";
  saveLanguage(currentLanguage);
  applyTranslations(currentLanguage);

  if (storyReaderModal && storyReaderModal.classList.contains("open")) {
    activePageIndex = 0;
    updateStoryPage();
  }
}

if (navToggle && mainNav) {
  navToggle.addEventListener("click", () => {
    const isOpen = mainNav.classList.toggle("open");
    navToggle.setAttribute("aria-expanded", String(isOpen));
  });
}

languageSelects.forEach((select) => {
  select.addEventListener("change", (event) => {
    setLanguage(event.target.value);
  });
});

